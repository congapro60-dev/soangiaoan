import {createArenaEvent, arenaEntries, arenaAnswer, arenaCombat, publicArena, arenaResults} from '../lib/arena-community.js';
import {createCampaign} from '../lib/campaign.js';
const camp = createCampaign({theme: 'historical', community: 'arena', grade: 10, maxLevel: 1}, 7);
const roster = Array.from({length: 26}, (_, i) => ({id: 'p' + i, name: 'HS ' + i, status: 'active', race: {mascot: i % 8}}));
const ev = createArenaEvent({roster, wall: 1000, triggerId: 't', seed: 42});
const rows = arenaEntries(ev, {});
console.log('bracket', ev.bracket.length, 'roster', ev.roster.length, 'dur', ev.duration);
const ev2 = createArenaEvent({roster: roster.slice(0, 25), wall: 1000, triggerId: 't', seed: 42});
console.log('odd bye', ev2.bracket.at(-1).bye, ev2.bracket.at(-1).right, ev2.roster.length);
const a = rows[0], b = rows.find(r => r.id === a.opponent);
const q = arenaAnswer(ev, camp, a, {answer: '0', step: 0, wall: ev.startAt + 10, requestId: 'r1'});
console.log('answer ok', q.ok, q.correct);
const A = {...q.entry, resource: 3};
const hit = arenaCombat(ev, {actor: A, target: b, action: 'attack', wall: ev.startAt + 20, requestId: 'r2'});
console.log('attack', hit.ok, hit.effect, hit.target.hp);
const bad = arenaCombat(ev, {actor: A, target: rows[5], action: 'attack', wall: ev.startAt + 20, requestId: 'r3'});
console.log('wrong target', bad.ok, bad.reason);
console.log('results', arenaResults(ev, rows).slice(0, 2).map(r => r.outcome + ':' + r.rank).join(','));
const pub = publicArena(ev, camp, rows, ev.startAt + 10, a.id);
const text = JSON.stringify(pub);
console.log('leaks expected/steps/seed:', text.includes('expected'), text.includes('"steps"'), text.includes('seed'));
console.log('has question/opponent:', !!pub.own.question, !!pub.own.opponent);
const t = publicArena(ev, camp, rows, ev.startAt + 10, a.id, true);
console.log('teacher has expected:', JSON.stringify(t).includes('expected'));
